#!/usr/bin/env node
/**
 * Migrates full schema, indexes, sequences, and rows from live MySQL `soccerbot` database
 * into PostgreSQL. Designed to run safely against localhost MySQL -> localhost PostgreSQL.
 *
 * Usage:
 *   node scripts/migrate-mysql-to-pg.js [--dry-run] [--drop-existing] [--create-db]
 *
 * Env vars read from .env:
 *   Source MySQL: DB_HOST, DB_PORT, DB_USER, DB_PASSWORD, DB_NAME
 *   Target PG:    PGHOST (default localhost), PGPORT (default 5432), PGUSER (default DB_USER),
 *                 PGPASSWORD (default DB_PASSWORD), PGDATABASE (default DB_NAME), or DATABASE_URL
 */
const mysql = require('mysql2/promise');
const { Client } = require('pg');
require('dotenv').config({ quiet: true });

const args = new Set(process.argv.slice(2));
const DRY_RUN = args.has('--dry-run');
const DROP_EXISTING = args.has('--drop-existing');
const CREATE_DB = args.has('--create-db');

const PG_RESERVED = new Set([
  'all', 'analyse', 'analyze', 'and', 'any', 'array', 'as', 'asc', 'asymmetric',
  'both', 'case', 'cast', 'check', 'collate', 'column', 'constraint', 'create',
  'current_date', 'current_time', 'current_timestamp', 'current_user', 'default',
  'deferrable', 'desc', 'distinct', 'do', 'else', 'end', 'except', 'false', 'fetch',
  'for', 'foreign', 'from', 'grant', 'group', 'having', 'in', 'initially', 'intersect',
  'into', 'leading', 'limit', 'localtime', 'localtimestamp', 'not', 'null', 'offset',
  'on', 'only', 'or', 'order', 'placing', 'primary', 'rank', 'references', 'returning',
  'select', 'session_user', 'some', 'symmetric', 'table', 'then', 'to', 'trailing',
  'true', 'union', 'unique', 'user', 'using', 'variadic', 'when', 'where', 'window', 'with'
]);

function quoteIdent(name) {
  const lower = String(name).toLowerCase();
  if (PG_RESERVED.has(lower) || !/^[a-z_][a-z0-9_]*$/.test(lower)) {
    return `"${lower.replace(/"/g, '""')}"`;
  }
  return `"${lower}"`;
}

function mapColumnType(col) {
  const dataType = String(col.DATA_TYPE || '').toLowerCase();
  const colType = String(col.COLUMN_TYPE || '').toLowerCase();
  const extra = String(col.EXTRA || '').toLowerCase();
  const isAutoInc = extra.includes('auto_increment');

  let pgType;
  if (dataType === 'bigint') {
    pgType = 'BIGINT';
  } else if (dataType === 'int' || dataType === 'integer' || dataType === 'mediumint') {
    pgType = 'INTEGER';
  } else if (dataType === 'smallint' || dataType === 'tinyint') {
    pgType = isAutoInc ? 'INTEGER' : 'SMALLINT';
  } else if (dataType === 'decimal' || dataType === 'numeric') {
    const p = col.NUMERIC_PRECISION || 10;
    const s = col.NUMERIC_SCALE || 2;
    pgType = `NUMERIC(${p}, ${s})`;
  } else if (dataType === 'float') {
    pgType = 'REAL';
  } else if (dataType === 'double' || dataType === 'real') {
    pgType = 'DOUBLE PRECISION';
  } else if (dataType === 'varchar') {
    pgType = `VARCHAR(${col.CHARACTER_MAXIMUM_LENGTH || 255})`;
  } else if (dataType === 'char') {
    pgType = `CHAR(${col.CHARACTER_MAXIMUM_LENGTH || 1})`;
  } else if (dataType === 'enum' || dataType === 'set') {
    pgType = 'VARCHAR(50)';
  } else if (dataType.includes('text')) {
    pgType = 'TEXT';
  } else if (dataType === 'date') {
    pgType = 'DATE';
  } else if (dataType === 'datetime' || dataType === 'timestamp') {
    pgType = 'TIMESTAMP';
  } else if (dataType === 'time') {
    pgType = 'TIME';
  } else if (dataType === 'json') {
    pgType = 'JSONB';
  } else if (dataType.includes('blob') || dataType.includes('binary')) {
    pgType = 'BYTEA';
  } else {
    pgType = 'TEXT';
  }

  let defClause = '';
  if (isAutoInc) {
    defClause = ' GENERATED BY DEFAULT AS IDENTITY';
  } else if (col.COLUMN_DEFAULT !== null && col.COLUMN_DEFAULT !== undefined) {
    const rawDef = String(col.COLUMN_DEFAULT).trim();
    const upperDef = rawDef.toUpperCase();
    if (upperDef === 'CURRENT_TIMESTAMP' || upperDef === 'CURRENT_TIMESTAMP()' || upperDef === 'NOW()') {
      defClause = ' DEFAULT CURRENT_TIMESTAMP';
    } else if (/^0000-00-00/.test(rawDef)) {
      defClause = '';
    } else if (/^-?\d+(\.\d+)?$/.test(rawDef) && (['SMALLINT', 'INTEGER', 'BIGINT', 'REAL', 'DOUBLE PRECISION'].includes(pgType) || pgType.startsWith('NUMERIC'))) {
      defClause = ` DEFAULT ${rawDef}`;
    } else if (upperDef !== 'NULL') {
      const escaped = rawDef.replace(/'/g, "''");
      defClause = ` DEFAULT '${escaped}'`;
    }
  }

  const isZeroDateDefault = col.COLUMN_DEFAULT && /^0000-00-00/.test(String(col.COLUMN_DEFAULT));
  const notNull = (String(col.IS_NULLABLE).toUpperCase() === 'NO' && !isZeroDateDefault) ? ' NOT NULL' : '';

  return `${quoteIdent(col.COLUMN_NAME)} ${pgType}${notNull}${defClause}`;
}

function sanitizeValue(val, col) {
  if (val === null || val === undefined) return null;
  const dt = String(col.DATA_TYPE || '').toLowerCase();
  if (val instanceof Date) {
    if (Number.isNaN(val.getTime())) return null;
    if (val.getFullYear() <= 1 || val.getFullYear() > 9999) return null;
    if (dt === 'date') {
      const y = val.getFullYear();
      const m = String(val.getMonth() + 1).padStart(2, '0');
      const d = String(val.getDate()).padStart(2, '0');
      return `${y}-${m}-${d}`;
    }
    return val;
  }
  if (typeof val === 'string' && /^0000-00-00/.test(val)) {
    return null;
  }
  return val;
}

async function ensurePgDatabase(pgConfig) {
  const targetDb = pgConfig.database;
  const adminClient = new Client({ ...pgConfig, database: 'postgres' });
  await adminClient.connect();
  try {
    const check = await adminClient.query('SELECT 1 FROM pg_database WHERE datname = $1', [targetDb]);
    if (check.rowCount === 0) {
      await adminClient.query(`CREATE DATABASE ${quoteIdent(targetDb)}`);
      console.log(`✅ Created PostgreSQL database "${targetDb}"`);
    } else {
      console.log(`ℹ️ PostgreSQL database "${targetDb}" already exists`);
    }
  } finally {
    await adminClient.end();
  }
}

async function main() {
  const mysqlConfig = {
    host: process.env.DB_HOST || 'localhost',
    port: parseInt(process.env.DB_PORT || '3306', 10),
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME || 'soccerbot',
    charset: 'utf8mb4'
  };

  const pgConfig = process.env.DATABASE_URL
    ? { connectionString: process.env.DATABASE_URL }
    : {
        host: process.env.PGHOST || 'localhost',
        port: parseInt(process.env.PGPORT || '5432', 10),
        user: process.env.PGUSER || process.env.DB_USER || 'postgres',
        password: process.env.PGPASSWORD || process.env.DB_PASSWORD,
        database: process.env.PGDATABASE || process.env.DB_NAME || 'soccerbot'
      };

  console.log(`🔌 Source MySQL: ${mysqlConfig.user}@${mysqlConfig.host}:${mysqlConfig.port}/${mysqlConfig.database}`);
  console.log(`🔌 Target PG:    ${pgConfig.connectionString || `${pgConfig.user}@${pgConfig.host}:${pgConfig.port}/${pgConfig.database}`}`);
  if (DRY_RUN) console.log('🧪 DRY-RUN mode enabled (no writes to PostgreSQL)');

  const mysqlConn = await mysql.createConnection(mysqlConfig);
  let pgClient = null;

  try {
    if (!DRY_RUN && CREATE_DB && !pgConfig.connectionString) {
      await ensurePgDatabase(pgConfig);
    }

    if (!DRY_RUN) {
      pgClient = new Client(pgConfig);
      await pgClient.connect();
      await pgClient.query(`
        CREATE OR REPLACE FUNCTION set_updated_at_timestamp()
        RETURNS TRIGGER AS $$
        BEGIN
          NEW.updated_at = CURRENT_TIMESTAMP;
          RETURN NEW;
        END;
        $$ LANGUAGE plpgsql;
      `);
    }

    const [tableRows] = await mysqlConn.query(`SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'`);
    const tableKey = Object.keys(tableRows[0] || {}).find(k => k.toLowerCase().startsWith('tables_in_'));
    const tables = tableRows.map(r => r[tableKey]).filter(Boolean);

    console.log(`📋 Found ${tables.length} tables in MySQL database '${mysqlConfig.database}'`);

    const summary = [];

    for (const rawTable of tables) {
      const pgTable = rawTable.toLowerCase();
      const [cols] = await mysqlConn.query(
        `SELECT COLUMN_NAME, COLUMN_TYPE, DATA_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA,
                CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE
         FROM information_schema.columns
         WHERE table_schema = ? AND table_name = ?
         ORDER BY ORDINAL_POSITION ASC`,
        [mysqlConfig.database, rawTable]
      );

      const [idxRows] = await mysqlConn.query(
        `SELECT INDEX_NAME, NON_UNIQUE, COLUMN_NAME, SEQ_IN_INDEX
         FROM information_schema.statistics
         WHERE table_schema = ? AND table_name = ?
         ORDER BY INDEX_NAME, SEQ_IN_INDEX ASC`,
        [mysqlConfig.database, rawTable]
      );

      const idxMap = new Map();
      for (const r of idxRows) {
        if (!idxMap.has(r.INDEX_NAME)) {
          idxMap.set(r.INDEX_NAME, { nonUnique: Number(r.NON_UNIQUE), cols: [] });
        }
        idxMap.get(r.INDEX_NAME).cols.push(quoteIdent(r.COLUMN_NAME));
      }

      const colDefs = cols.map(mapColumnType);
      const pk = idxMap.get('PRIMARY');
      if (pk && pk.cols.length > 0) {
        colDefs.push(`PRIMARY KEY (${pk.cols.join(', ')})`);
      }

      for (const [idxName, info] of idxMap.entries()) {
        if (idxName === 'PRIMARY' || info.nonUnique !== 0) continue;
        const safeConstraint = `${pgTable}_${idxName.toLowerCase()}`.slice(0, 60);
        colDefs.push(`CONSTRAINT ${quoteIdent(safeConstraint)} UNIQUE (${info.cols.join(', ')})`);
      }

      const createTableSql = `CREATE TABLE IF NOT EXISTS ${quoteIdent(pgTable)} (\n  ${colDefs.join(',\n  ')}\n);`;
      const extraIndexSqls = [];
      for (const [idxName, info] of idxMap.entries()) {
        if (idxName === 'PRIMARY' || info.nonUnique === 0) continue;
        const safeIdx = `idx_${pgTable}_${idxName.toLowerCase()}`.slice(0, 60);
        extraIndexSqls.push(`CREATE INDEX IF NOT EXISTS ${quoteIdent(safeIdx)} ON ${quoteIdent(pgTable)} (${info.cols.join(', ')});`);
      }

      const hasUpdatedAt = cols.some(c => String(c.COLUMN_NAME).toLowerCase() === 'updated_at');
      const [mysqlCountRows] = await mysqlConn.query(`SELECT COUNT(*) AS cnt FROM \`${rawTable}\``);
      const mysqlCount = Number(mysqlCountRows[0]?.cnt || 0);

      if (DRY_RUN) {
        console.log(`\n--- ${pgTable} (${mysqlCount} rows) ---`);
        console.log(createTableSql);
        extraIndexSqls.forEach(s => console.log(s));
        summary.push({ table: pgTable, mysqlCount, pgCount: '(dry-run)' });
        continue;
      }

      if (DROP_EXISTING) {
        await pgClient.query(`DROP TABLE IF EXISTS ${quoteIdent(pgTable)} CASCADE`);
      }
      await pgClient.query(createTableSql);
      for (const idxSql of extraIndexSqls) {
        await pgClient.query(idxSql);
      }
      if (hasUpdatedAt) {
        const trgName = `trg_${pgTable}_updated_at`.slice(0, 60);
        await pgClient.query(`DROP TRIGGER IF EXISTS ${quoteIdent(trgName)} ON ${quoteIdent(pgTable)}`);
        await pgClient.query(`
          CREATE TRIGGER ${quoteIdent(trgName)}
          BEFORE UPDATE ON ${quoteIdent(pgTable)}
          FOR EACH ROW EXECUTE FUNCTION set_updated_at_timestamp();
        `);
      }

      const existingPg = await pgClient.query(`SELECT COUNT(*)::int AS cnt FROM ${quoteIdent(pgTable)}`);
      const existingCount = Number(existingPg.rows[0]?.cnt || 0);
      if (existingCount > 0 && !DROP_EXISTING) {
        console.log(`⏩ ${pgTable}: PostgreSQL already has ${existingCount} rows (pass --drop-existing to reload).`);
        summary.push({ table: pgTable, mysqlCount, pgCount: existingCount });
        continue;
      }

      if (mysqlCount > 0) {
        const [rows] = await mysqlConn.query(`SELECT * FROM \`${rawTable}\``);
        const colNamesSql = cols.map(c => quoteIdent(c.COLUMN_NAME)).join(', ');
        const BATCH = Math.max(1, Math.min(500, Math.floor(30000 / Math.max(1, cols.length))));

        await pgClient.query('BEGIN');
        try {
          for (let offset = 0; offset < rows.length; offset += BATCH) {
            const slice = rows.slice(offset, offset + BATCH);
            const values = [];
            const rowPlaceholders = slice.map((row, rIdx) => {
              const phs = cols.map((col, cIdx) => {
                const rawVal = row[col.COLUMN_NAME];
                values.push(sanitizeValue(rawVal, col));
                return `$${rIdx * cols.length + cIdx + 1}`;
              });
              return `(${phs.join(', ')})`;
            });
            const insertSql = `INSERT INTO ${quoteIdent(pgTable)} (${colNamesSql}) VALUES ${rowPlaceholders.join(', ')}`;
            await pgClient.query(insertSql, values);
          }
          await pgClient.query('COMMIT');
        } catch (batchErr) {
          await pgClient.query('ROLLBACK');
          throw new Error(`Failed migrating table '${pgTable}': ${batchErr.message}`);
        }
      }

      // Sync identity sequence if table has an auto-increment column
      const autoCol = cols.find(c => String(c.EXTRA || '').toLowerCase().includes('auto_increment'));
      if (autoCol) {
        const colIdent = String(autoCol.COLUMN_NAME).toLowerCase();
        const seqRes = await pgClient.query(`SELECT pg_get_serial_sequence($1, $2) AS seq`, [pgTable, colIdent]);
        const seqName = seqRes.rows[0]?.seq;
        if (seqName) {
          await pgClient.query(`
            SELECT setval(
              $1,
              COALESCE((SELECT MAX(${quoteIdent(colIdent)}) FROM ${quoteIdent(pgTable)}), 1),
              (SELECT COUNT(*) > 0 FROM ${quoteIdent(pgTable)})
            )
          `, [seqName]);
        }
      }

      const finalPg = await pgClient.query(`SELECT COUNT(*)::int AS cnt FROM ${quoteIdent(pgTable)}`);
      const pgCount = Number(finalPg.rows[0]?.cnt || 0);
      const statusMark = pgCount === mysqlCount ? '✅' : '❌';
      console.log(`${statusMark} ${pgTable}: MySQL=${mysqlCount} -> PostgreSQL=${pgCount}`);
      summary.push({ table: pgTable, mysqlCount, pgCount });
    }

    const mismatches = summary.filter(s => !DRY_RUN && s.mysqlCount !== s.pgCount);
    console.log(`\n🎉 Migration finished: ${summary.length} tables processed, mismatches=${mismatches.length}`);
    if (mismatches.length > 0) {
      console.error('❌ Mismatched tables:', mismatches);
      process.exitCode = 1;
    }
  } finally {
    await mysqlConn.end();
    if (pgClient) await pgClient.end();
  }
}

main().catch((err) => {
  console.error('❌ Migration failed:', err);
  process.exit(1);
});
